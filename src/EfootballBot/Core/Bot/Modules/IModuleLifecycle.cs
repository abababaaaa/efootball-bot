namespace EfootballBot.Core.Bot.Modules;

/// <summary>
/// 模块生命周期回调：引擎在「引擎侧动作影响模块状态」时通知场景，场景自己决定怎么复位。
/// 为什么不让引擎直接 cast 到具体场景：那会让引擎认识每一个模块（改一个模块要改引擎），
/// 而这层接口只要求「谁需要复位谁就实现」，引擎永远只认接口。
/// </summary>
public interface IModuleLifecycle
{
    /// <summary>
    /// 引擎重启过游戏（只打关键比赛跳过普通场次）。<paramref name="success"/> = 重启是否成功。
    /// 实现者应清掉旧会话的界面/比赛记忆（新窗口是冷启动），并作废当前场次。
    /// </summary>
    void OnGameRestarted(bool success);
}





