///  - 新增 Token：先在 Themes/Tokens.xaml 加默认值（暗色），再在这三张表里各加一行；
///  - 漏加会被 <see cref="Validate"/> 在启动时点名（以前漏加就是「亮色主题下某块还是暗的」）。
