    /// <summary>按主题名取调色板（未知名字回落到暗色）。</summary>
    public static IReadOnlyDictionary<string, string> For(string? themeName) => themeName switch
    {
        ThemeManager.Light => LightColors,
        ThemeManager.DeepBlue => DeepBlueColors,
        _ => DarkColors,
    };

    /// <summary>自检：三张表与默认（暗色）表相比缺了哪些 Token。返回空表示完整。</summary>
    public static string[] Validate()
    {
        static string[] Diff(IReadOnlyDictionary<string, string> other, string label)
        {
            var missing = DarkColors.Keys.Except(other.Keys).Select(k => $"{label} 缺 {k}").ToList();
            var extra = other.Keys.Except(DarkColors.Keys).Select(k => $"{label} 多 {k}（暗色表没有）").ToList();
            return [.. missing, .. extra];
        }

        return [.. Diff(LightColors, "亮色"), .. Diff(DeepBlueColors, "深蓝")];
    }

